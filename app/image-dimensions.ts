export function getImageDimensions(src: string): ImageDimensions {
  const path = src.split("?")[0];
  const direct = imageDimensions[path];
  if (direct) {
    return direct;
  }

  try {
    const decoded = decodeURIComponent(path);
    const decodedMatch = imageDimensions[decoded];
    if (decodedMatch) {
      return decodedMatch;
    }
  } catch {
    // Keep the original path when it is not valid URI encoding.
  }

  throw new Error(`Missing image dimensions for ${src}`);
}
